/**
 * Starter flowcharts for the builder's example browser, kept as pseudocode and
 * drawn on demand. `examples.test.ts` draws every one, converts it back and runs
 * it with `inputs`, which must produce `output`.
 */
export type FlowchartExample = {
  id: string;
  title: string;
  category: FlowchartCategory;
  /** One line: what the program does and what it teaches. */
  description: string;
  /** Short concept chips, also searched. */
  concepts: string[];
  code: string;
  /** Sample inputs shown in the preview ("Try it with…") and used by the test. */
  inputs: string[];
  output: string;
};

